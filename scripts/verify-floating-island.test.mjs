// Structural check for the generated floating-island voxel volume consumed by
// ThreeCanvas (readonly render step). Guards the concept-art silhouette from
// floating_island.jpg: full sheer cap, accelerating taper, narrow keel.
// Run with: npm test
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(
  join(root, "src", "data", "floating-island.ts"),
  "utf8",
);

const num = (name) => {
  const m = source.match(new RegExp(`export const ${name} = (\\d+);`));
  assert.ok(m, `missing export ${name}`);
  return Number(m[1]);
};
const W = num("ISLAND_W");
const D = num("ISLAND_D");
const H = num("ISLAND_H");

// The exported array literal is plain JS once the type annotation is
// stripped; evaluate it to verify the generated bytes as shipped.
const literal = source.match(
  /export const FLOATING_ISLAND: IslandVoxel\[\]\[\]\[\] = (\[[\s\S]*?\]);\n\n/,
);
assert.ok(literal, "missing FLOATING_ISLAND literal");
const volume = eval(literal[1]);

const solidCount = (z) =>
  volume[z].flat().reduce((sum, voxel) => sum + voxel, 0);

describe("floating-island", () => {
  it("is a 12x12x10 volume of 0/1 matching the default grid", () => {
    assert.equal(W, 12);
    assert.equal(D, 12);
    assert.equal(H, 10);
    assert.equal(volume.length, H);
    for (const layer of volume) {
      assert.equal(layer.length, D);
      for (const row of layer) {
        assert.equal(row.length, W);
        for (const voxel of row) {
          assert.ok(voxel === 0 || voxel === 1, `bad voxel ${voxel}`);
        }
      }
    }
  });

  it("keeps a solid 3-layer cap flush under the terrain", () => {
    for (let z = 0; z < 3; z++) {
      assert.equal(solidCount(z), W * D, `cap layer z=${z} is not solid`);
    }
  });

  it("tapers monotonically below sheer upper cliffs", () => {
    assert.ok(
      solidCount(3) >= 130,
      `expected sheer cliffs at z=3, got ${solidCount(3)}/144`,
    );
    for (let z = 4; z < H; z++) {
      assert.ok(
        solidCount(z) <= solidCount(z - 1),
        `layer z=${z} (${solidCount(z)}) bulges past z=${z - 1} (${solidCount(z - 1)})`,
      );
    }
  });

  it("ends in a small centered keel with a solid core on every layer", () => {
    for (let z = 3; z < H; z++) {
      assert.ok(solidCount(z) > 0, `layer z=${z} is hollow`);
    }
    const tip = solidCount(H - 1);
    assert.ok(tip >= 1 && tip <= 8, `expected a narrow keel, got ${tip}`);
    for (let y = 0; y < D; y++) {
      for (let x = 0; x < W; x++) {
        if (volume[H - 1][y][x] === 1) {
          assert.ok(
            Math.hypot(x - (W - 1) / 2, y - (D - 1) / 2) <= 2,
            `keel voxel drifts to (${x},${y})`,
          );
        }
      }
    }
  });

  it("stays centered layer by layer", () => {
    for (let z = 3; z < H; z++) {
      let sx = 0;
      let sy = 0;
      let n = 0;
      for (let y = 0; y < D; y++) {
        for (let x = 0; x < W; x++) {
          if (volume[z][y][x] === 1) {
            sx += x;
            sy += y;
            n++;
          }
        }
      }
      assert.ok(
        Math.hypot(sx / n - (W - 1) / 2, sy / n - (D - 1) / 2) <= 1.5,
        `layer z=${z} leans off-center`,
      );
    }
  });
});
