// Generates the sample floating-island voxel volume and writes it to
// src/data/floating-island.ts.
//
// Usage: npm run generate:island
//
// The volume is ISLAND_W x ISLAND_D x ISLAND_H voxels of 0 (empty) / 1
// (present). Index order is [z][y][x]: z = 0 is the layer directly beneath
// the terrain surface, z increases downward to the island tip. y is the grid
// row, x is the grid column, matching grid-store cell coordinates on the
// default 12x12 grid.
//
// Shape: iceberg-style floating island matching
// .muse-session/concept_art/floating_island_1.jpg — a full rounded-square
// plateau with sheer upper cliffs, an accelerating taper through the mid
// strata, and a narrow jagged keel, with seeded value noise so regeneration
// is deterministic.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const W = 12;
const D = 12;
const H = 10;
const SEED = 1337;

// Deterministic PRNG (mulberry32).
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = rng(SEED);

// Coarse 3D value-noise lattice with trilinear interpolation, so the rock
// reads as chunky strata instead of per-voxel static.
const LATTICE = 4;
const lattice = [];
for (let i = 0; i < (LATTICE + 1) ** 3; i++) lattice.push(rand());

function noise(x, y, z) {
  const fx = (x / (W - 1)) * LATTICE;
  const fy = (y / (D - 1)) * LATTICE;
  const fz = (z / (H - 1)) * LATTICE;
  const x0 = Math.min(Math.floor(fx), LATTICE - 1);
  const y0 = Math.min(Math.floor(fy), LATTICE - 1);
  const z0 = Math.min(Math.floor(fz), LATTICE - 1);
  const tx = fx - x0;
  const ty = fy - y0;
  const tz = fz - z0;
  const at = (ix, iy, iz) =>
    lattice[ix + (LATTICE + 1) * (iy + (LATTICE + 1) * iz)];
  const lerp = (a, b, t) => a + (b - a) * t;
  return lerp(
    lerp(
      lerp(at(x0, y0, z0), at(x0 + 1, y0, z0), tx),
      lerp(at(x0, y0 + 1, z0), at(x0 + 1, y0 + 1, z0), tx),
      ty,
    ),
    lerp(
      lerp(at(x0, y0, z0 + 1), at(x0 + 1, y0, z0 + 1), tx),
      lerp(at(x0, y0 + 1, z0 + 1), at(x0 + 1, y0 + 1, z0 + 1), tx),
      ty,
    ),
    tz,
  );
}

const cx = (W - 1) / 2;
const cy = (D - 1) / 2;

// Rounded-square distance (superellipse, p = 4): the concept island is a
// chunky plateau with rounded corners, not a cone — Chebyshev (p = inf)
// would keep sharp corners, Euclidean (p = 2) would round it to a disc.
function shapeDist(x, y) {
  const dx = Math.abs(x - cx);
  const dy = Math.abs(y - cy);
  return (dx ** 4 + dy ** 4) ** (1 / 4);
}

// Half-width profile: sheer cliffs just under the cap (the concept's icy
// upper walls drop near-vertically), then an accelerating taper to the
// dark keel. Corner superellipse distance is ~6.55, edge midpoint 5.5.
const CAP_Z = 3; // z < CAP_Z is solid, flush under the terrain layer
function radiusAt(z) {
  if (z < CAP_Z) return Infinity;
  const t = (z - (CAP_Z - 1)) / (H - 1 - (CAP_Z - 1));
  return 0.95 + (6.9 - 0.95) * (1 - Math.pow(t, 1.7));
}

const volume = [];
for (let z = 0; z < H; z++) {
  const layer = [];
  const r = radiusAt(z);
  for (let y = 0; y < D; y++) {
    const row = [];
    for (let x = 0; x < W; x++) {
      if (z < CAP_Z) {
        row.push(1); // solid cap: sits flush under the terrain layer
        continue;
      }
      const d = shapeDist(x, y);
      const wobble = (noise(x, y, z) - 0.5) * 2.2;
      row.push(d + wobble < r ? 1 : 0);
    }
    layer.push(row);
  }
  volume.push(layer);
}

// Guarantee: no hollow gap in the middle, every layer keeps its core.
for (let z = 0; z < H; z++) {
  let solid = 0;
  for (let y = 0; y < D; y++) {
    for (let x = 0; x < W; x++) solid += volume[z][y][x];
  }
  if (solid === 0) {
    volume[z][5][5] = 1;
    volume[z][5][6] = 1;
    volume[z][6][5] = 1;
    volume[z][6][6] = 1;
  }
}

// ASCII preview + stats for eyeballing the taper.
let total = 0;
for (let z = 0; z < H; z++) {
  let count = 0;
  const r = radiusAt(z);
  console.log(
    `--- layer z=${z} (${z < CAP_Z ? "solid cap" : `radius ${r.toFixed(2)}`}) ---`,
  );
  for (let y = 0; y < D; y++) {
    let line = "";
    for (let x = 0; x < W; x++) {
      count += volume[z][y][x];
      line += volume[z][y][x] ? "#" : ".";
    }
    console.log(line);
  }
  console.log(`solid: ${count}/${W * D}\n`);
  total += count;
}
console.log(`total solid voxels: ${total}/${W * D * H}`);

const layers = volume
  .map(
    (layer, z) =>
      `  // z=${z}\n  [\n${layer.map((row) => `    [${row.join(",")}],`).join("\n")}\n  ],`,
  )
  .join("\n");

const out = `// Sample floating-island voxel volume: ${W} x ${D} x ${H} of 0/1.
// GENERATED by scripts/generate-floating-island.mjs — do not edit by hand.
// Regenerate with: npm run generate:island
//
// Index order is [z][y][x]: z = 0 is the layer directly beneath the terrain
// surface, z increases downward to the island tip. 1 = rock present,
// 0 = empty. Future iterations may replace 1s with texture/material ids.

export const ISLAND_W = ${W};
export const ISLAND_D = ${D};
export const ISLAND_H = ${H};

export type IslandVoxel = 0 | 1;

export const FLOATING_ISLAND: IslandVoxel[][][] = [
${layers}
];

export function isIslandSolid(x: number, y: number, z: number): boolean {
  if (x < 0 || y < 0 || z < 0 || x >= ISLAND_W || y >= ISLAND_D || z >= ISLAND_H) {
    return false;
  }
  return FLOATING_ISLAND[z][y][x] === 1;
}
`;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
writeFileSync(join(root, "src", "data", "floating-island.ts"), out);
console.log("wrote src/data/floating-island.ts");
